//! Golden-output tests for the documentation generators (man / markdown / yaml / ReST).
//! These catch silent regressions in doc structure (headers, sections, footers).
const std = @import("std");
const cobra = @import("cobra.zig");
const Command = cobra.Command;
const pflag = cobra.command_mod.pflag;

const gpa = std.testing.allocator;

const emptyRun = struct {
    fn f(cmd: *Command, args: [][]const u8) void {
        _ = cmd;
        _ = args;
    }
}.f;

fn setupCmds() struct { root: Command, child: Command } {
    return .{
        .root = .{
            .use = "root",
            .short = "root short",
            .long = "root long description",
            .example = "  root --name x",
            .run = emptyRun,
        },
        .child = .{ .use = "child", .short = "child short", .run = emptyRun },
    };
}

test "genMan renders roff header and core sections" {
    const io = std.Io.Threaded.global_single_threaded.*.io();
    var cmds = setupCmds();
    cmds.root.addCommand(gpa, &.{&cmds.child});
    defer cmds.root.deinit(gpa);

    var buf: [8192]u8 = undefined;
    var w = std.Io.Writer.fixed(&buf);
    try cobra.man_doc_mod.genMan(gpa, &cmds.root, io, null, &w);
    const out = std.Io.Writer.buffered(&w);

    try std.testing.expect(std.mem.startsWith(u8, out, ".TH \"ROOT\" \"1\""));
    try std.testing.expect(std.mem.indexOf(u8, out, ".SH NAME\nroot") != null);
    try std.testing.expect(std.mem.indexOf(u8, out, ".SH SYNOPSIS") != null);
    try std.testing.expect(std.mem.indexOf(u8, out, ".SH DESCRIPTION\nroot long description") != null);
    try std.testing.expect(std.mem.indexOf(u8, out, ".SH OPTIONS") != null);
    try std.testing.expect(std.mem.indexOf(u8, out, ".SH EXAMPLE") != null);
    try std.testing.expect(std.mem.indexOf(u8, out, ".SH SEE ALSO") != null);
    try std.testing.expect(std.mem.indexOf(u8, out, "Auto generated by spf13/cobra") != null);
}

