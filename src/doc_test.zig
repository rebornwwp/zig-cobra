test "genMarkdownTree writes one file per command" {
    const io = std.Io.Threaded.global_single_threaded.*.io();
    var cmds = setupCmds();
    cmds.root.addCommand(gpa, &.{&cmds.child});
    defer cmds.root.deinit(gpa);

    var tmp = std.testing.tmpDir(.{});
    defer tmp.cleanup();

    // tmpDir lives at .zig-cache/tmp/<sub_path> relative to cwd; genMarkdownTree
    // resolves paths against cwd, so pass the full cwd-relative directory.
    var dir_buf: [128]u8 = undefined;
    const dir = try std.fmt.bufPrint(&dir_buf, "{s}{c}{s}", .{ std.testing.TmpDir.parent_dir_path, std.fs.path.sep, &tmp.sub_path });

    try cobra.doc_mod.genMarkdownTree(gpa, &cmds.root, io, dir);

    // Both docs must exist.
    for ([_][]const u8{ "root.md", "root_child.md" }) |fname| {
        var path_buf: [160]u8 = undefined;
        const path = try std.fmt.bufPrint(&path_buf, "{s}/{s}", .{ dir, fname });
        const file = std.Io.Dir.cwd().openFile(io, path, .{}) catch |err| {
            std.debug.print("expected {s} to exist: {s}\n", .{ path, @errorName(err) });
            return error.TestFailed;
        };
        file.close(io);
    }
}
