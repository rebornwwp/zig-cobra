//! Markdown doc generation. Maps from doc/md_docs.go
const std = @import("std");
const command_mod = @import("../command.zig");
const Command = command_mod.Command;
const util = @import("util.zig");

pub const markdown_extension = ".md";

/// Custom link/file-prepender callback (Zig stand-in for Go closures).
pub const DocHandler = struct {
    ctx: ?*anyopaque = null,
    call: *const fn (ctx: ?*anyopaque, name: []const u8) []const u8,
};

fn identity(ctx: ?*anyopaque, name: []const u8) []const u8 {
    _ = ctx;
    return name;
}
fn emptyStr(_: ?*anyopaque, _: []const u8) []const u8 {
    return "";
}

fn printOptions(gpa: std.mem.Allocator, cmd: *Command, w: *std.Io.Writer) !void {
    cmd.mergePersistentFlags(gpa);
    const local = cmd.localFlagsView();
    if (util.hasAvailableFlags(local)) {
        try w.print("### Options\n\n```\n", .{});
        util.writeFlagUsages(w, local);
        try w.print("```\n\n", .{});
    }
    const inherited = cmd.inheritedFlagsView();
    if (util.hasAvailableFlags(inherited)) {
        try w.print("### Options inherited from parent commands\n\n```\n", .{});
        util.writeFlagUsages(w, inherited);
        try w.print("```\n\n", .{});
    }
}

/// genMarkdown creates markdown output (Go: GenMarkdown).
pub fn genMarkdown(gpa: std.mem.Allocator, cmd: *Command, io: std.Io, w: *std.Io.Writer) anyerror!void {
    return genMarkdownCustom(gpa, cmd, io, w, .{ .call = identity });
}

/// genMarkdownCustom creates markdown output with a custom link handler
/// (Go: GenMarkdownCustom).
pub fn genMarkdownCustom(gpa: std.mem.Allocator, cmd: *Command, io: std.Io, w: *std.Io.Writer, link_handler: DocHandler) anyerror!void {
    _ = io;
    cmd.initDefaultHelpCmd(gpa);
    cmd.initDefaultHelpFlag(gpa);
    cmd.mergePersistentFlags(gpa);

    const name = cmd.commandPath();
    try w.print("## {s}\n\n", .{name});
    try w.print("{s}\n\n", .{util.trimTrailingWhitespaces(cmd.short)});
    if (cmd.long.len > 0) {
        try w.print("### Synopsis\n\n{s}\n\n", .{cmd.long});
    }
    if (cmd.runnable()) {
        try w.print("```\n{s}\n```\n\n", .{cmd.useLine()});
    }
    if (cmd.example.len > 0) {
        try w.print("### Examples\n\n```\n{s}\n```\n\n", .{cmd.example});
    }

    try printOptions(gpa, cmd, w);

    if (util.hasSeeAlso(cmd)) {
        try w.print("### SEE ALSO\n\n", .{});
        if (cmd.parent) |parent| {
            const pname = parent.commandPath();
            var link_buf: [512]u8 = undefined;
            const link = util.docFilename(parent, markdown_extension, &link_buf);
            try w.print("* [{s}]({s})\t - {s}\n", .{ pname, link_handler.call(link_handler.ctx, link), util.trimTrailingWhitespaces(parent.short) });
            // Go: propagate parent's DisableAutoGenTag to this command.
            var p: ?*Command = cmd.parent;
            while (p) |cur| : (p = cur.parent) {
                if (cur.disable_auto_gen_tag) {
                    cmd.disable_auto_gen_tag = true;
                    break;
                }
            }
        }

        var buf: [512]u8 = undefined;
        for (cmd.getCommands()) |child| {
            if (!child.isAvailableCommand() and !child.isAdditionalHelpTopicCommand()) continue;
            const cname = child.commandPath();
            const clink = util.docFilename(child, markdown_extension, &buf);
            try w.print("* [{s}]({s})\t - {s}\n", .{ cname, link_handler.call(link_handler.ctx, clink), util.trimTrailingWhitespaces(child.short) });
        }
        try w.print("\n", .{});
    }

    if (!cmd.disable_auto_gen_tag) {
        try w.print("###### Auto generated by spf13/cobra\n", .{});
    }
}

/// genMarkdownTree creates markdown ref files for cmd and all descendants (Go: GenMarkdownTree).
pub fn genMarkdownTree(gpa: std.mem.Allocator, cmd: *Command, io: std.Io, dir: []const u8) anyerror!void {
    return genMarkdownTreeCustom(gpa, cmd, io, dir, .{ .call = emptyStr }, .{ .call = identity });
}

/// genMarkdownTreeCustom — tree variant with file prepender and link handler
/// (Go: GenMarkdownTreeCustom).
pub fn genMarkdownTreeCustom(
    gpa: std.mem.Allocator,
    cmd: *Command,
    io: std.Io,
    dir: []const u8,
    file_prepender: DocHandler,
    link_handler: DocHandler,
) anyerror!void {
    for (cmd.getCommands()) |c| {
        if (!c.isAvailableCommand() and !c.isAdditionalHelpTopicCommand()) continue;
        try genMarkdownTreeCustom(gpa, c, io, dir, file_prepender, link_handler);
    }

    var name_buf: [512]u8 = undefined;
    const basename = util.docFilename(cmd, markdown_extension, &name_buf);
    var path_buf: [1024]u8 = undefined;
    const filename = try joinPath(&path_buf, dir, basename);

    const prepended = file_prepender.call(file_prepender.ctx, filename);

    const file = try std.Io.Dir.cwd().createFile(io, filename, .{});
    var fbuf: [8192]u8 = undefined;
    var file_writer = std.Io.File.Writer.init(file, io, &fbuf);
    const w = &file_writer.interface;
    try if (prepended.len > 0) w.print("{s}", .{prepended});
    try genMarkdownCustom(gpa, cmd, io, w, link_handler);
    try file_writer.flush();
    file.close(io);
}

fn joinPath(buf: []u8, dir: []const u8, name: []const u8) ![]const u8 {
    var w = std.Io.Writer.fixed(buf);
    if (dir.len > 0) {
        try w.print("{s}", .{dir});
        try if (!std.mem.endsWith(u8, dir, "/")) w.print("/", .{});
    }
    try w.print("{s}", .{name});
    if (w.end > buf.len) return error.PathTooLong;
    return buf[0..w.end];
}
